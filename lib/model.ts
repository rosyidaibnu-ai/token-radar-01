// Token Radar's model, version radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks pre-token protocols by an implied token value derived only from the
// snapshot's own figures. No protocol name is ever special-cased: the same function
// scores every row, and every number below can be recomputed from the snapshot.
//
//   multiple     = the category's own comparable: the median FDV/TVL (mcap_usd / tvl_usd)
//                  of the tokenized protocols in the same category, when at least four
//                  of them report both figures; otherwise the global median across all
//                  tokenized protocols. Clamped to [0.05, 1.00].
//   base         = tvl_usd x multiple
//   growth       = clamp(change_7d, -60, 120) per cent (null counts as 0)
//   growthMult   = 1 + (growth / 100) x 0.6
//   maturity     = 0.7 + min(age_days, 1095) / 1095 x 0.5 (age unknown: 365 days)
//   implied      = max(1, round(base x growthMult x maturity))
//
// A protocol is pre-token when its record carries no token at all (no market cap, no
// CoinGecko id, no symbol). The board ranks every rankable pre-token protocol: the
// watchlist is the floor, never the ceiling, and the early rows are the pre-token
// protocols below the floor the radar exists to find. Live-token protocols are kept
// apart and shown as the market's own values, never mixed into the ranked board.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  multiple_min: number;
  multiple_max: number;
  min_peers: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.6,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.7,
  maturity_range: 0.5,
  maturity_days: 1095,
  unknown_age_days: 365,
  multiple_min: 0.05,
  multiple_max: 1.0,
  min_peers: 4,
};

